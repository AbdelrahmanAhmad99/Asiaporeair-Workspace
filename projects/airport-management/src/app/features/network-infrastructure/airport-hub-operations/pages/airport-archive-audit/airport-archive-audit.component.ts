
import {
  ChangeDetectionStrategy,
  Component,
  OnDestroy,
  OnInit,
  computed,
  inject,
  signal,
} from '@angular/core';
import { CommonModule } from '@angular/common';
import { ReactiveFormsModule } from '@angular/forms';
import { ActivatedRoute, Router } from '@angular/router';

import { AirportsStore, AuditFilter } from '../../store/airports.store';
import { ArchivedAirportListComponent } from '../../components/archived-airport-list/archived-airport-list.component';

@Component({
  selector: 'aoms-airport-archive-audit',
  standalone: true,
  imports: [
    CommonModule,
    ReactiveFormsModule,
    ArchivedAirportListComponent,
  ],
  changeDetection: ChangeDetectionStrategy.OnPush,
  templateUrl: './airport-archive-audit.component.html',
  styleUrl: './airport-archive-audit.component.scss',
})
export class AirportArchiveAuditComponent implements OnInit, OnDestroy {
  protected readonly store = inject(AirportsStore);
  private readonly router = inject(Router);
  private readonly route = inject(ActivatedRoute);

  // ── Store passthrough signals ─────────────────────────────────────────
  protected readonly records = this.store.filteredAuditRecords;
  protected readonly loading = this.store.loading;
  protected readonly isRestoring = this.store.isRestoring;
  protected readonly restoringCode = this.store.restoringIataCode;
  protected readonly auditError = this.store.auditError;
  protected readonly currentFilter = this.store.auditFilter;
  protected readonly toastQueue = this.store.toastQueue;
  protected readonly deactivatedCount = this.store.deactivatedCount;
  protected readonly totalCount = this.store.auditTotalCount;

  /** Set<string> of currently active IATA codes — passed to the list for status derivation. */
  protected readonly activeSet = computed<Set<string>>(
    () => new Set(this.store.airports().map(a => a.iataCode))
  );

  // ── Local UI state ────────────────────────────────────────────────────

  /** Local search input value (controls the store via debounce). */
  protected readonly searchQuery = signal<string>('');

  /** Debounce handle for the search input. */
  private _searchDebounce: ReturnType<typeof setTimeout> | null = null;

  /** Track auto-dismiss timers for toasts. */
  private _toastTimers = new Map<string, ReturnType<typeof setTimeout>>();

  // ── Filter options for the toggle bar ─────────────────────────────────
  protected readonly filterOptions: { label: string; value: AuditFilter; icon: string }[] = [
    { label: 'All Records', value: 'all', icon: 'M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5' },
    { label: 'Deactivated', value: 'deleted', icon: 'm14.74 9-.346 9m-4.788 0L9.26 9m9.968-3.21c.342.052.682.107 1.022.166m-1.022-.165L18.16 19.673a2.25 2.25 0 0 1-2.244 2.077H8.084a2.25 2.25 0 0 1-2.244-2.077L4.772 5.79m14.456 0a48.108 48.108 0 0 0-3.478-.397m-12 .562c.34-.059.68-.114 1.022-.165m0 0a48.11 48.11 0 0 1 3.478-.397m7.5 0v-.916c0-1.18-.91-2.164-2.09-2.201a51.964 51.964 0 0 0-3.32 0c-1.18.037-2.09 1.022-2.09 2.201v.916m7.5 0a48.667 48.667 0 0 0-7.5 0' },
    { label: 'Operational', value: 'active', icon: 'M9 12.75 11.25 15 15 9.75M21 12a9 9 0 1 1-18 0 9 9 0 0 1 18 0z' },
  ];

  // ─────────────────────────────────────────────────────────────────────

  ngOnInit(): void {
    this.store.fetchFullAuditLog();

    // Check if a specific iataCode was passed as a query param from the Details view
    const queryIata = this.route.snapshot.queryParamMap.get('iataCode');
    if (queryIata) {
      this.searchQuery.set(queryIata.toUpperCase());
      this.store.setAuditSearch(queryIata.toUpperCase());
    }
  }

  ngOnDestroy(): void {
    this.store.clearAuditView();
    if (this._searchDebounce) clearTimeout(this._searchDebounce);
    this._toastTimers.forEach(t => clearTimeout(t));
    this._toastTimers.clear();
  }

  // ── Navigation ────────────────────────────────────────────────────────

  protected returnToOperations(): void {
    this.router.navigate(['aoms/network-infrastructure/airport-hub-operations/dashboard']);
  }

  // ── Filter toggle ──────────────────────────────────────────────────────

  protected setFilter(filter: AuditFilter): void {
    this.store.setAuditFilter(filter);
  }

  // ── Search ────────────────────────────────────────────────────────────

  protected onSearchInput(event: Event): void {
    const query = (event.target as HTMLInputElement).value;
    this.searchQuery.set(query);

    if (this._searchDebounce) clearTimeout(this._searchDebounce);
    this._searchDebounce = setTimeout(() => {
      this.store.setAuditSearch(query);
    }, 200);
  }

  protected clearSearch(): void {
    this.searchQuery.set('');
    this.store.setAuditSearch('');
  }

  // ── Restore ────────────────────────────────────────────────────────────

  protected onRestore(iataCode: string): void {
    this.store.restoreHub(iataCode);

    // Auto-dismiss any toast for this code after 4s
    // (the toast is generated by the store on success/failure)
    // We schedule a dismiss check after 4.5s
    setTimeout(() => {
      const toast = this.store.toastQueue().find(t => t.iataCode === iataCode);
      if (toast) {
        this._scheduleToastDismiss(toast.id);
      }
    }, 100);
  }

  protected dismissToast(id: string): void {
    this.store.dismissToast(id);
    const t = this._toastTimers.get(id);
    if (t) { clearTimeout(t); this._toastTimers.delete(id); }
  }

  // ── Refresh ───────────────────────────────────────────────────────────

  protected refresh(): void {
    this.store.fetchFullAuditLog();
  }

  // ── Private helpers ───────────────────────────────────────────────────

  private _scheduleToastDismiss(id: string): void {
    if (this._toastTimers.has(id)) return;
    const timer = setTimeout(() => {
      this.store.dismissToast(id);
      this._toastTimers.delete(id);
    }, 4000);
    this._toastTimers.set(id, timer);
  }
}